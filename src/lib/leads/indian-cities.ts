/** Merge static list with extra cities from DB (e.g. lead records) */
export function mergeCities(...extra: (string | null | undefined)[]): string[] {
  const set = new Set(INDIAN_CITIES);
  extra.forEach((c) => {
    const trimmed = c?.trim();
    if (trimmed) set.add(trimmed);
  });
  return [...set].sort((a, b) => a.localeCompare(b));
}
